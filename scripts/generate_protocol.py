"""Generate language models and OpenAPI from the canonical schema. No network."""
from pathlib import Path
import json, re, sys, subprocess
root=Path(__file__).resolve().parents[1]
schema=json.loads((root/'protocol/schema.json').read_text('utf-8'))
go=['// Code generated by scripts/generate_protocol.py; DO NOT EDIT.','package protocol','import "time"']
ts=['// Generated from protocol/schema.json. Do not edit.']
kt=['// Generated from protocol/schema.json. Do not edit.','package dev.chronos.agents.protocol','import org.json.JSONObject']
def name(k):return ''.join({'id':'ID','os':'OS'}.get(x,x.title()) for x in k.split('_'))
def types(p):
 if p.get('x-go-type')=='int':return 'int','number','Long'
 if '$ref'in p:return (p['$ref'].split('/')[-1],)*3
 if p.get('format')=='date-time':return 'time.Time','string','String'
 t=p['type']
 if isinstance(t,list):return 'map[string]any','Record<string, unknown> | null','JSONObject?'
 if t=='object':return 'map[string]Metric','Record<string, Metric>','Map<String, Metric>'
 return {'string':('string','string','String'),'integer':('int64','number','Long'),'boolean':('bool','boolean','Boolean')}[t]
for n,d in schema['$defs'].items():
 go.append('type '+n+' struct {');ts.append('export interface '+n+' {');fields=[]
 for key,p in d['properties'].items():
  g,t,k=types(p);go.append(f' {name(key)} {g} `json:"{key}"`');ts.append(f' {key}{"" if key in d["required"] else "?"}: {t};');fields.append(f' val {key}: {k}')
 go.append('}');ts.append('}');kt.append('data class '+n+'(\n'+',\n'.join(fields)+'\n)')
kt.append('object Wire { const val VERSION = 1; val statuses = setOf('+','.join('"'+v+'"' for v in schema['$defs']['Metric']['properties']['status']['enum'])+') }')
api={'openapi':'3.1.0','info':{'title':'Chronos Agents API','version':'0.1.0'},'components':{'schemas':schema['$defs'],'securitySchemes':{'device':{'type':'http','scheme':'bearer'},'reader':{'type':'http','scheme':'bearer'}}},'paths':{'/api/v1/ingest':{'post':{'security':[{'device':[]}],'requestBody':{'required':True,'content':{'application/json':{'schema':{'$ref':'#/components/schemas/Envelope'}}}},'responses':{'202':{'description':'Accepted or duplicate'},'401':{'description':'Revoked or invalid device credential'},'422':{'description':'Invalid telemetry'}}}}}}
def refs(v):
 if isinstance(v,dict):return {k:(x.replace('#/$defs/','#/components/schemas/') if k=='$ref' else refs(x)) for k,x in v.items()}
 if isinstance(v,list):return [refs(x) for x in v]
 return v
files={'internal/protocol/models.go':'\n'.join(go)+'\n','web/protocol.ts':'\n'.join(ts)+'\n','clients/android/app/src/main/java/dev/chronos/agents/protocol/Models.kt':'\n'.join(kt)+'\n','protocol/openapi.json':json.dumps(refs(api),ensure_ascii=False,indent=2)+'\n'}
for f,data in files.items():
 if f.endswith(".go"):data=subprocess.run(["gofmt"],input=data,text=True,capture_output=True,check=True).stdout
 path=root/f
 if '--check'in sys.argv:
  if not path.exists() or path.read_text('utf-8')!=data:raise SystemExit('Generated file differs: '+f)
 else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(data,'utf-8')
print('Protocol models '+('verified' if '--check'in sys.argv else 'generated'))
